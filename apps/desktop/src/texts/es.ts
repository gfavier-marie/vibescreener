const plural = pluralFor('es');

function day(iso: string) {
  const days = daysAgo(iso);
  if (days === 0) return 'hoy';
  if (days === 1) return 'ayer';
  return shortDate('es', iso);
}

function since(iso: string) {
  const min = minutesAgo(iso);
  if (min < 1) return 'desde hace un momento';
  if (min < 60) return `desde hace ${min} min`;
  if (min < 24 * 60) return `desde hace ${Math.floor(min / 60)} h`;
  return daysAgo(iso) === 1 ? 'desde ayer' : `desde el ${day(iso)}`;
}

